"""Class to evaluate the RAG system answer.
RAGEvaluator: The logic that uses an LLM to "Judge" the Agent
"""
# from typing import Literal, List
from typing import Any
from dataclasses import dataclass
from pydantic_ai import Agent, AgentRunResult
from pydantic_evals.evaluators import Evaluator
from pydantic_evals.evaluators.evaluator import EvaluationReason
from src.models import RAGResponse, JudgeOutput


@dataclass
class RAGEvaluator(Evaluator[str, AgentRunResult[RAGResponse]]): # Evaluator[InputType, OutputType]
    """"Evaluator to check faithfulness and relevance of the answer generated by the RAG system."""
    
    async def evaluate(self, query:str, agent_result: AgentRunResult[RAGResponse]) -> dict[str, Any]:
        # It is async because in case we had more queries we don't want to wait for the LLM response before running another request
        # We creat a "judge agent" and tell it to use our JudgeOutput "Report card"
        judge_agent = Agent(
            'google-gla:gemini-2.5-pro', 
            output_type=JudgeOutput,
            system_prompt = (
                "You are a question/answer auditor. Your job is to evaluate if an AI answer: "
                "is faithful to the source and relevant to the user question (actually addresses the user question)."  
            )
        )
        
        # With the type hint the IDE will know .output is a RAGResponse
        rag_data = agent_result.output
        
        # The teacher (Evaluator) asks the judge to fill out the Report Card (JudgeOutput)
        # All the next strings are automatically concatenated into one single prompt in Python.
        # We access the data through .data
        result = await judge_agent.run(
            f"Question: {query}\n"
            f"Answer: {rag_data.answer}\n"
            f"Source: {rag_data.source_snippet}\n"
        )
    
        # Now we pull the data out of the Report Card to gve to the framework
        # result.output is an instance of JudgeOutput
        
        # Return the formatted string
        score_summary = (
            f"Faith: {result.output.faithfulness_score} | "
            f" Relevance: {result.output.relevance_score} | "
            f" Reasoning: {result.output.reasoning}"
        )
        
        return {
            "score": result.output.faithfulness_score, # We put here faithfulness to see it at a glance
            "summary": score_summary
        }
        
